/**
 * Extracts a clean slug/name for the project from user prompt.
 */
export function extractProjectSlug(prompt: string, fallback = 'smfta-webapp'): string {
  if (!prompt) return fallback;
  const cleaned = prompt
    .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
    .trim()
    .split(/\s+/)
    .slice(0, 4)
    .join('-')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}-]/gu, '');
  return cleaned && cleaned.length >= 2 ? cleaned : fallback;
}

