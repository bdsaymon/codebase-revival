/**
 * Builds a ZIP file containing the full-stack project files.
 */
export function buildFullStackZip(project: FullStackProjectSpec): Uint8Array {
  const entries: Record<string, Uint8Array> = {};
  for (const file of project.files) {
    entries[file.path] = strToU8(file.content);
  }
  return zipSync(entries);
}

/**
 * Download helper for browser environments.
 */
export function downloadFullStackZip(project: FullStackProjectSpec): void {
  if (typeof document === 'undefined') return;
  const bytes = buildFullStackZip(project);
  const copy = new Uint8Array(bytes.length);
  copy.set(bytes);
  const blob = new Blob([copy], { type: 'application/zip' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${project.name}-fullstack-project.zip`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
